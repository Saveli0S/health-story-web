const assert=require('node:assert/strict');
const path=require('node:path');
const {chromium,webkit,devices}=require('playwright-core');
const mobile=process.argv.includes('--iphone'),base=process.env.HEALTH_PREVIEW_URL||'http://127.0.0.1:8764/';
(async()=>{
  const browser=mobile?await webkit.launch():await chromium.launch({channel:'chrome'});
  try{
    const ctx=await browser.newContext(mobile?devices['iPhone 13']:{viewport:{width:1280,height:900}});
    const page=await ctx.newPage();page.setDefaultTimeout(12000);page.setDefaultNavigationTimeout(60000);
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    const url=base+'?section=exams&profile=anna&space=demo';
    await page.goto(url);await page.locator('main [data-action=newExam]').click();
    const d=page.locator('dialog'),params=d.locator('[name=paramValue]'),date=d.locator('[name=date]');
    const today=await page.evaluate(()=>todayLocal());
    assert.equal(await date.inputValue(),today);
    await d.locator('[data-example]').click();await params.first().waitFor();
    assert.equal(await date.inputValue(),'2026-11-12','explicit date overrides the automatic date');
    const original='03-phantom-report.pdf';
    await d.locator('[name=images]').setInputFiles(path.join(__dirname,'medical-corpus','attachments','files',original));
    await d.getByText('Снимки готовы к сохранению.').waitFor();
    const firstPreview=d.locator('[data-originals] details').filter({hasText:original});
    await firstPreview.locator('summary').click();await firstPreview.getByLabel('Страница оригинала').waitFor();
    await firstPreview.locator('summary').click();
    await params.first().fill('44 × 15 × 14');
    await d.locator('[name=visit]').selectOption('a1');
    await params.first().focus();
    await d.locator('[data-action=close]').click();
    await page.locator('main [data-action=resumeExam]').waitFor();
    assert.equal(await page.locator('main [data-action=resumeExam]').count(),1,'editable draft remains after close');
    const before=await page.evaluate(()=>({count:current().exams.length,outbound:JSON.stringify(consultContext(['visit:a1']).data),published:allFiles().map(f=>f.name)}));
    assert.equal(before.count,0);assert(!before.outbound.includes('44 × 15 × 14'));assert(!before.published.includes(original));
    await page.evaluate(async()=>{await navigator.serviceWorker.ready});
    await page.waitForFunction(()=>Boolean(navigator.serviceWorker.controller));
    await ctx.setOffline(true);await page.reload();await page.locator('main [data-action=resumeExam]').click();
    assert.equal(await params.first().inputValue(),'44 × 15 × 14');
    assert.equal(await params.first().evaluate(el=>el===document.activeElement),true,JSON.stringify(await page.evaluate(()=>({field:document.activeElement.name,tag:document.activeElement.tagName,saved:current().examDrafts[0].position,ids:current().examDrafts[0].parameters.map(p=>p.id)}))));
    const pdf=d.locator('[data-originals] details').filter({hasText:original});if(!await pdf.evaluate(el=>el.open))await pdf.locator('summary').click();
    await pdf.getByLabel('Страница оригинала').selectOption('2');
    await d.locator('[data-action=close]').click();
    await page.locator('main [data-action=resumeExam]').click();
    await d.locator('[data-originals] details[open] select').waitFor();
    assert.equal(await d.locator('[data-originals] details[open] select').inputValue(),'2');
    await d.locator('[name=reviewed]').check();
    await d.getByRole('button',{name:'Сохранить обследование'}).click();
    await d.getByRole('heading',{name:'Заключение врача'}).waitFor();
    await ctx.setOffline(false);
    assert.deepEqual(await page.evaluate(()=>[current().examDrafts.length,current().exams.length,current().files.filter(f=>f.examId===current().exams[0].id).length]),[0,1,2]);
    await d.getByRole('button',{name:'Закрыть',exact:true}).click();
    await page.locator('main [data-action=newExam]').click();
    const addProtocol=async(name,text)=>{
      await d.locator('[name=protocol]').setInputFiles({name,mimeType:'text/plain',buffer:Buffer.from(text)});
      await d.getByText('Откройте оригинал и сверьте перенесённые поля. Дополните пропуски вручную.').waitFor();
      await d.locator('button.primary:enabled').waitFor();
    };
    await addProtocol('undated.txt','Протокол УЗИ\nОбласть исследования: Учебная зона\nДата печати: 14.11.2026\nЗаключение: Учебное заключение.');
    assert.equal(await date.inputValue(),today,'a printing date must not replace today');
    await d.getByRole('button',{name:'Отложить сверку'}).click();
    await page.reload();await page.locator('main [data-action=resumeExam]').click();
    assert.equal(await date.inputValue(),today,'automatic date survives reopening the draft');
    await addProtocol('dated.txt','Протокол УЗИ\nДата обследования: 15.11.2026');
    assert.equal(await date.inputValue(),'2026-11-15','an explicit date replaces the resumed automatic date');
    await date.fill('2026-11-16');
    await addProtocol('other-date.txt','Протокол УЗИ\nДата обследования: 17.11.2026');
    assert.equal(await date.inputValue(),'2026-11-16','the user-selected date is preserved');
    await d.locator('[name=reviewed]').check();
    await d.getByRole('button',{name:'Сохранить обследование'}).click();
    await d.getByRole('heading',{name:'Заключение врача'}).waitFor();
    assert(await page.evaluate(()=>current().exams.some(e=>e.date==='2026-11-16')));
    assert.deepEqual(errors,[]);console.log('PASS '+(mobile?'WebKit':'Chrome')+' exam dates, offline draft, originals and the verified exam');
  }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
