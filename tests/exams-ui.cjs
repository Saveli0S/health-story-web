// Synthetic instrumental findings and originals, using the normal profile UI.
const assert=require('node:assert/strict');
const path=require('node:path');
const {chromium,webkit,devices}=require('playwright-core');
const mobile=process.argv.includes('--iphone');
const base=process.env.HEALTH_PREVIEW_URL||'http://127.0.0.1:8764/';
const corpus=path.join(__dirname,'medical-corpus','attachments','files');
(async()=>{
  const browser=mobile?await webkit.launch():await chromium.launch({channel:'chrome'});
  try{
    const options=mobile?devices['iPhone 13']:{viewport:{width:1440,height:960}};
    const ctx=await browser.newContext(options),p=await ctx.newPage(),errors=[];
    p.setDefaultTimeout(15000);p.on('pageerror',e=>errors.push(e.message));
    const d=p.locator('dialog'),f=name=>d.locator('[name="'+name+'"]').first();
    const action=(name,scope=d)=>scope.locator('[data-action="'+name+'"]').first().click();
    const save=()=>d.getByRole('button',{name:'Сохранить обследование'}).click();
    await p.goto(base+'?space=demo&profile=anna&section=exams');await action('newExam',p.locator('main'));
    await d.getByText('Загрузить учебный протокол УЗИ').click();
    await d.getByText(/Откройте оригинал и сверьте/).waitFor();
    assert.equal(await f('date').inputValue(),'2026-11-12');
    assert.equal(await f('method').inputValue(),'УЗИ');
    assert.equal(await d.locator('.exam-parameter').count(),3);
    assert.equal(await f('paramValue').inputValue(),'42 × 15 × 14');
    assert.equal(await f('paramUnit').inputValue(),'мм');
    await f('paramValue').fill('43 × 15 × 14');
    await f('clinic').fill('Тестовая клиника 77');await f('visit').selectOption('a1');
    await f('images').setInputFiles(['01-phantom.png','05-phantom-dicom.zip'].map(n=>path.join(corpus,n)));
    await d.getByText('Снимки готовы к сохранению.').waitFor();
    await save();assert(await f('reviewed').isVisible());await f('reviewed').check();await save();
    await d.getByRole('heading',{name:'Заключение врача'}).waitFor();
    assert.match(await d.innerText(),/43 × 15 × 14 мм/);
    await d.getByRole('button',{name:/01-phantom.png/}).click();await d.locator('img.paper-preview').waitFor();
    await action('back');await d.getByRole('button',{name:/05-phantom-dicom.zip/}).click();
    await d.getByRole('link',{name:'Скачать оригинал'}).waitFor();await action('back');
    await action('consult');assert(await d.locator('input[value^="exam:"]').isChecked());
    await f('question').fill('Собери данные обследования');await d.locator('#consult-form button.primary').click();
    const saved=await p.evaluate(()=>current().consultations.at(-1).prompt);
    assert(saved.includes('43 × 15 × 14')&&!saved.includes('Тестовая клиника 77')&&!saved.includes('phantom'));
    await action('close');await p.reload();await p.locator('#section-filter').fill('эхоструктура');await action('exam',p.locator('#listing'));
    await action('editExam');await f('description').fill('Уточнённое описание');await save();
    await d.getByText('Уточнённое описание',{exact:true}).waitFor();
    await action('visit');await d.getByRole('heading',{name:'Результаты обследований'}).waitFor();
    assert.equal(await d.locator('[data-action=exam]').count(),1);
    const clinical=await p.evaluate(()=>{
      const id=current().exams[0].id,ep=visitById('a1')[7];
      return [consultContext(['exam:'+id,'visit:a1','episode:'+ep]).data.обследования.length,makePayload('a1').обследования.length];
    });
    assert.deepEqual(clinical,[1,1]);
    await action('close');await action('newExam',p.locator('main'));
    await f('protocol').setInputFiles(path.join(corpus,'03-phantom-report.pdf'));
    await d.getByText(/Откройте оригинал и сверьте/).waitFor({timeout:90000});
    assert.match(await f('conclusion').inputValue(),/семь ступеней/);
    if(!await d.locator('[data-originals] details').evaluate(el=>el.open))await d.locator('[data-originals] summary').click();
    await d.locator('.source-preview canvas').waitFor();
    await f('method').selectOption('Рентгенография');await f('date').fill('2026-11-12');await f('reviewed').check();await save();
    await d.getByRole('heading',{name:'Заключение врача'}).waitFor();await action('close');
    await p.goto(base+'?space=demo&profile=misha&section=exams');await action('newExam',p.locator('main'));
    await f('method').selectOption('МРТ');await f('date').fill('2026-11-14');
    await f('images').setInputFiles(path.join(corpus,'02-phantom-photo.jpg'));await save();
    await d.getByText('Заключение пока не добавлено.').waitFor();
    await p.goto(base+'?role=child&section=exams');
    await action('exam',p.locator('#listing'));assert.match(await d.innerText(),/МРТ/);
    assert.equal(await d.locator('[data-action=editExam]').count(),0);
    assert.equal(await p.locator('main [data-action=newExam]').count(),0);
    assert.equal(await p.locator('main [data-action=exam]').count(),1);
    assert(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await p.goto(base+'?space=demo&profile=anna&section=exams');
    await action('newExam',p.locator('main'));
    await d.getByText('Выбрать из документов профиля').click();
    const png=await f('existing').locator('option').filter({hasText:'01-phantom.png'}).getAttribute('value');
    await f('existing').selectOption(png);await d.locator('[data-existing]').click();
    await d.getByText('Снимки готовы к сохранению.').waitFor();
    await f('method').selectOption('Другое');await f('date').fill('2026-11-12');await save();
    await d.getByRole('heading',{name:'Заключение врача'}).waitFor();
    assert.equal(await p.evaluate(()=>current().files.filter(f=>f.name==='01-phantom.png').length),1);
    const copy=await p.evaluate(async()=>{
      const key=toBase64(crypto.getRandomValues(new Uint8Array(32)));
      const archive=await encryptedArchive(await archiveKey(key));return {key,bytes:toBase64(new Uint8Array(await archive.arrayBuffer()))};
    });
    const clean=await browser.newContext(options),restored=await clean.newPage();
    await restored.goto(base+'?section=settings');await restored.locator('main [data-action=archive]').click();
    const restore=restored.locator('dialog');
    await restore.locator('[data-action=importBackup]').click();
    await restore.locator('[name=archive]').setInputFiles({name:'test.health',mimeType:'application/octet-stream',buffer:Buffer.from(copy.bytes,'base64')});
    await restore.locator('[name=key]').fill(copy.key);
    await restore.getByRole('button',{name:'Проверить копию'}).click();
    await restore.getByText(/Копия проверена/).waitFor();
    await restore.locator('[name=replace]').check();
    await Promise.all([restored.waitForEvent('load'),restore.getByRole('button',{name:'Восстановить'}).click()]);
    await restored.goto(base+'?section=exams&profile=anna');
    await restored.locator('#listing').getByRole('button',{name:/Рентгенография/}).click();
    await restore.getByRole('button',{name:/03-phantom-report.pdf/}).click();
    await restore.locator('.source-preview canvas').waitFor();
    await clean.close();

    const sheet=await ctx.newPage();
    await sheet.setContent('<article style="background:white;color:black;font:32px Arial;width:800px;padding:40px"><h2>Протокол УЗИ</h2><p>Дата исследования: 12.11.2026</p><p>Параметры:</p><p>Длина: 42 мм</p><p>Заключение: Контуры ровные.</p></article>');
    const photo=await sheet.locator('article').screenshot();await sheet.close();
    await action('close');await action('newExam',p.locator('main'));
    await f('protocol').setInputFiles({name:'Протокол.png',mimeType:'image/png',buffer:photo});
    await d.getByText(/Откройте оригинал и сверьте/).waitFor({timeout:90000});
    assert.equal(await f('paramValue').inputValue(),'42');assert.match(await f('conclusion').inputValue(),/Контуры/iu);
    assert.deepEqual(errors,[]);console.log('PASS',mobile?'WebKit iPhone':'desktop Chrome','· import PDF/TXT/PNG OCR, correction, originals, consultation, child access, encrypted restore to clean browser');
  }finally{await browser.close()}
})().catch(err=>{console.error(err);process.exitCode=1});
